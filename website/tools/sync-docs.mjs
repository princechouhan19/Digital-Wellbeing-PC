#!/usr/bin/env node
/**
 * Copies the repository's Markdown into the website as a generated module.
 *
 *   node tools/sync-docs.mjs          # write src/content/docs.generated.ts
 *   node tools/sync-docs.mjs --check  # exit 1 when the copy is out of date
 *
 * The website never reads the repository at request time, so the same output
 * ships in a standalone deployment. Run it after editing anything in docs/,
 * PRIVACY.md or CHANGELOG.md. The npm scripts predev and prebuild call it.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..", "..")
const outFile = join(here, "..", "src", "content", "docs.generated.ts")

/** Order matters: it is the reading order on /docs. */
const sources = [
  "docs/USER_GUIDE.md",
  "docs/TROUBLESHOOTING.md",
  "docs/CLI_REFERENCE.md",
  "docs/DEVELOPER_GUIDE.md",
  "docs/ARCHITECTURE.md",
  "docs/PERFORMANCE.md",
  "docs/ATTENTION_WELLNESS.md",
  "docs/RELEASING.md",
  "docs/UX_GUIDELINES.md",
  "docs/QA_APP_LOCKER.md",
  "PRIVACY.md",
  "ROADMAP.md",
  "CHANGELOG.md",
]

const slugFor = (file) =>
  file
    .replace(/^docs\//, "")
    .replace(/\.md$/, "")
    .toLowerCase()
    .replace(/_/g, "-")

const entries = sources.map((file) => {
  const full = join(root, file)
  if (!existsSync(full)) throw new Error(`missing source document: ${relative(root, full)}`)
  const markdown = readFileSync(full, "utf8")
  return { file, slug: slugFor(file), words: Math.round(markdown.split(/\s+/).length / 10) * 10, markdown }
})

const body = `// GENERATED by website/tools/sync-docs.mjs. Do not edit.
// Source files: ${sources.join(", ")}
export type SourceDoc = { file: string; slug: string; words: number; markdown: string }

export const sourceDocs: SourceDoc[] = ${JSON.stringify(entries, null, 2)}
`

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : ""
  if (current !== body) {
    console.error("docs are stale: run `npm run docs` and commit src/content/docs.generated.ts")
    process.exit(1)
  }
  console.log(`docs are current (${entries.length} files)`)
} else {
  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(outFile, body)
  console.log(`wrote ${relative(root, outFile)} (${entries.length} files, ${(body.length / 1024).toFixed(0)} KB)`)
}
